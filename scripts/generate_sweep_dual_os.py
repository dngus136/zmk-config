#!/usr/bin/env python3
"""Generate Sweep's two runtime OS profiles from the existing shared keymap.

The shared 3x5/shortcut/combos/behaviors files remain the source of truth.
Run after changing any of them. No third-party Python dependencies required.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
INC = ROOT / 'config/includes'
LAYERS = ('DEF', 'NUM', 'SYM', 'NAV', 'SYS')
SELECT = list(range(20)) + list(range(21, 31)) + list(range(33, 37))


def strip_comments(s):
    return re.sub(r'/\*.*?\*/|//[^\n]*', '', s, flags=re.S)


def replace_words(s, mapping):
    return re.sub(r'\b(' + '|'.join(map(re.escape, sorted(mapping, key=len, reverse=True))) + r')\b',
                  lambda m: mapping[m[0]], s)


def main():
    source = (INC / '3x5.dtsi').read_text()
    shortcuts = strip_comments((INC / 'shortcut.dtsi').read_text())
    # This boundary is the existing top-level Windows branch, after the nested
    # MAC_OS/I_PAD language selector. Fail rather than silently selecting wrong.
    boundary = shortcuts.rfind('#else')
    windows = dict(re.findall(r'#define\s+(\w+)\s+([^\n]+)', shortcuts[boundary:]))
    assert windows['C_CPY'] == 'LC(C)' and windows['LANG'] == 'RALT'

    # Keep the repository's original Windows language key; macOS uses the new
    # Control+Option+Space shortcut. No host-side language setup is changed.
    raw_layers = re.findall(r'(\w+_layer)\s*\{\s*display-name = "(\w+)";\s*bindings = <LAYER_FROM38\((.*?)\)>;\s*\};', source, re.S)
    assert [x[1] for x in raw_layers] == list(LAYERS)
    parsed = []
    for node, name, body in raw_layers:
        bindings = [x.strip() for x in strip_comments(body).replace('\\\n', ' ').split(',')]
        assert len(bindings) == 38, (name, len(bindings))
        assert len([bindings[i] for i in SELECT]) == 34
        parsed.append((node, name, bindings))

    win_map = {**windows, **{x: 'WIN_' + x for x in LAYERS},
               'NAV_SPC': '&win_nav_ht 0 SPC', 'SYS_TAB': '&win_sys_ht 0 TAB',
               'NUM_BSPC': '&win_num_ht 0 BSPC'}
    win_layers = [(node + '_win', name, [replace_words(b, win_map) for b in bindings])
                  for node, name, bindings in parsed]
    # &to (Shift+layer latch) disables WIN_DEF. Resolve transparent bindings to
    # Windows base explicitly so latched Windows layers never fall into macOS.
    win_base = win_layers[0][2]
    for _, _, bindings in win_layers:
        for i, b in enumerate(bindings):
            if b == '&trans':
                bindings[i] = win_base[i]

    mac_layers = [(node, name, list(bindings)) for node, name, bindings in parsed]
    # SYS physical W (position 1) is unused on both profiles.
    assert mac_layers[4][2][1] == win_layers[4][2][1] == '&none'
    mac_layers[4][2][1] = '&to WIN_DEF'
    win_layers[4][2][1] = '&to DEF'

    parts = ['// Generated by scripts/generate_sweep_dual_os.py. Do not edit directly.',
             '// SYS + physical W switches profiles and returns to the new DEF.',
             '#include <behaviors.dtsi>', '#include <dt-bindings/zmk/keys.h>',
             '#include <dt-bindings/zmk/bt.h>', '#include <dt-bindings/zmk/outputs.h>',
             '#include <behaviors/rgbled_widget.dtsi>', '']
    parts += [f'#define {name} {i}' for i, name in enumerate(LAYERS)]
    parts += [f'#define WIN_{name} {i+5}' for i, name in enumerate(LAYERS)]
    parts += ['', '#include "shortcut.dtsi"', '#include "behaviors.dtsi"',
              '#include "mouse.dtsi"', '#include "macros.dtsi"',
              '#include "combos.dtsi"', '']

    # Only the three layer hold-taps need their own Windows targets. Home-row,
    # navigation hold-taps, reset, and all swappers retain their original timing.
    behaviors = (INC / 'behaviors.dtsi').read_text()
    hold_section = behaviors[behaviors.index('        morph_num0:'):behaviors.index('        // Swapper')]
    hold_section = re.sub(r'^\s*#define[^\n]*\n', '\n', hold_section, flags=re.M)
    behavior_map = {name: 'win_' + name for name in
                    ('morph_num0', 'num_ht', 'num_layer_hold',
                     'morph_nav0', 'nav_ht', 'nav_layer_hold',
                     'morph_sys0', 'sys_ht', 'sys_layer_hold')}
    hold_section = replace_words(hold_section, {**behavior_map, **{x: 'WIN_'+x for x in LAYERS}})
    parts += ['/ {', '    behaviors {', hold_section, '    };', '    keymap {',
              '        compatible = "zmk,keymap";']
    for prefix, layers in [('MAC', mac_layers), ('WIN', win_layers)]:
        for node, name, bindings in layers:
            parts += [f'        {node} {{', f'            display-name = "{prefix} {name}";',
                      '            bindings = <LAYER_FROM38( \\']
            starts = [(0, 10), (10, 20), (20, 32), (32, 38)]
            for lo, hi in starts:
                comma = ',' if hi < 38 else ''
                parts.append('                ' + ', '.join(bindings[lo:hi]) + comma + ' \\')
            parts += ['            )>;', '        };']
    parts += ['    };', '};', '']

    # Mirror combo layer scopes as well: Windows select-all must send Ctrl+A,
    # and F+J in any Windows latched layer must return to WIN_DEF.
    combos = (INC / 'combos.dtsi').read_text()
    win_combos = []
    for line in combos.splitlines():
        if line.startswith('COMBO('):
            line = re.sub(r'^COMBO\((\w+)', r'COMBO(win_\1', line)
            win_combos.append(replace_words(line, win_map))
    assert len(win_combos) == len(re.findall(r'^COMBO\(', combos, re.M))
    parts += ['/ {', '    combos {', '\n'.join(win_combos), '    };', '};', '']
    result = '\n'.join(parts)
    target = INC / 'sweep-dual-os.dtsi'
    target.write_text(result)
    print(f'Generated {target.relative_to(ROOT)}: 10 layers x 34 keys; '
          f'{len(win_combos)} combos per profile; SYS/W toggles 0 <-> 5.')


if __name__ == '__main__':
    main()
